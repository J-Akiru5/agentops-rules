/**
 * Deterministic integrator.
 *
 * No model logic: the gates below are the only way develop moves. The integrator:
 *   1. re-reads the contract from the authoritative plan source and checks revision/acks/dependencies;
 *   2. verifies the source commit is reachable from the remote;
 *   3. checks develop has not moved unexpectedly and is not checked out in another worktree;
 *   4. refuses diffs outside the contract's ownership;
 *   5. builds a candidate in a scratch worktree, merges --no-ff, and runs the verification profile;
 *   6. runs an authorized development migration if the contract declares one;
 *   7. commits a tool-generated evidence summary;
 *   8. advances develop with a compare-and-swap ref update, pushes, and checks origin;
 *   9. only then marks the task integrated/done.
 *
 * On any failure develop stays at its last verified commit, the source branch is preserved, and the
 * task returns to a recoverable state.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { runDevelopmentMigration } from "./dbplane.mjs";
import { loadPlan, matchesAny, scopeViolations } from "./planlib.mjs";
import { Refusal, ResourceDeferral, runProfile } from "./runner.mjs";
import { acquireLock, getAgent, getTask, recordEvent, releaseLock, updateTask } from "./state.mjs";

function git(cwd, args) {
  return execFileSync("git", ["-C", cwd, ...args], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    maxBuffer: 32 * 1024 * 1024,
  }).trim();
}

function tryGit(cwd, args) {
  try {
    return git(cwd, args);
  } catch {
    return null;
  }
}

function candidatePathFor(taskId) {
  const root = path.join(os.tmpdir(), "agentops", "integration");
  fs.mkdirSync(root, { recursive: true });
  return path.join(root, `${taskId}-${Date.now()}`);
}

function removeCandidate(repo, candidate) {
  if (!fs.existsSync(candidate)) return { removed: true };
  try {
    git(repo, ["worktree", "remove", candidate]);
    return { removed: true };
  } catch (error) {
    return { removed: false, reason: error.message };
  }
}

function fail(db, taskId, agent, reason, extra = {}) {
  updateTask(db, taskId, { state: "integration_failed", blocked_reason: reason });
  recordEvent(db, { taskId, agent, kind: "integration_failed", message: reason, data: extra });
}

function developCheckedOut(repo) {
  const porcelain = git(repo, ["worktree", "list", "--porcelain"]);
  const entries = porcelain.split(/\r?\n/);
  let current = null;
  for (const line of entries) {
    if (line.startsWith("worktree ")) current = { path: line.slice(9) };
    else if (line.startsWith("branch ") && current) current.branch = line.slice(7);
    else if (line === "" && current) {
      if (current.branch === "refs/heads/develop") return current;
      current = null;
    }
  }
  if (current?.branch === "refs/heads/develop") return current;
  return null;
}

function evidenceSummary({ taskId, contract, mergeSha, mergeTree, profile, result, migration, agent }) {
  const lines = [
    "---",
    `task: ${taskId}`,
    `commit: ${mergeSha}`,
    `tree: ${mergeTree}`,
    `profile: ${profile}`,
    `result: ${result.status}`,
    `migration: ${contract.database_migration ?? "none"}`,
    `integrator: ${agent}`,
    `integrated_at: ${new Date().toISOString()}`,
    "---",
    "",
    `# Evidence — ${taskId}`,
    "",
    `Tool-generated by agentctl. Authoritative records live in \`.git/agentops/state.db\` and the logs beside it.`,
    "",
    "| check | command | exit | level | log |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const check of result.checks) {
    lines.push(
      `| ${check.id} | \`${String(check.command).replaceAll("|", "\\|")}\` | ${check.exit} | ${check.level} | \`${check.log}\` |`,
    );
  }
  if (migration) {
    lines.push(
      "",
      `Migration: target project \`${migration.target.projectRef}\`, exit ${migration.migrate.exitCode}, verified ${migration.ok}.`,
    );
  }
  lines.push("", "This file is added after verification; the verified code tree is the merge commit above.");
  return `${lines.join("\n")}\n`;
}

export async function integrateTask(ctx) {
  const { db, repo, commonDir, taskId, agent, planSource = "auto" } = ctx;
  const plan = loadPlan(repo, { source: planSource });
  if (plan.errors.length > 0) {
    throw new Refusal(`plan validation failed:\n${plan.errors.map((entry) => `  - ${entry}`).join("\n")}`);
  }
  const policy = plan.policy;
  const target = policy.integration.target_branch;
  const remote = policy.integration.remote ?? "origin";
  const entry = plan.tasks.find((task) => task.meta?.id === taskId);
  if (!entry) throw new Refusal(`contract ${taskId} not found in plan source ${plan.source.label}`);
  const contract = entry.meta;

  const task = getTask(db, taskId);
  if (!task) throw new Refusal(`task ${taskId} is not known to the state database; run plan sync first`);
  const agentRow = getAgent(db, agent);
  if (!agentRow) throw new Refusal(`agent ${agent} is not registered (agentctl agent register --id ${agent} --role integrator)`);
  const allowedRoles = policy.integration.allow_agents ?? ["integrator", "lead"];
  if (!allowedRoles.includes(agentRow.role)) {
    throw new Refusal(`agent ${agent} has role "${agentRow.role}"; integration requires one of: ${allowedRoles.join(", ")}`);
  }
  if (task.state !== "submitted") throw new Refusal(`task ${taskId} is ${task.state}; only submitted tasks integrate`);
  if (Number(task.contract_rev) !== Number(contract.rev)) {
    throw new Refusal(
      `contract revision mismatch: state.db=${task.contract_rev}, plan=${contract.rev}. Run "agentctl plan sync" and retry.`,
    );
  }
  const ack = db
    .prepare("SELECT * FROM acks WHERE task_id = ? AND agent = ?")
    .get(taskId, task.owner_agent ?? "");
  if (!ack || Number(ack.revision) !== Number(task.contract_rev)) {
    throw new Refusal(`owner ${task.owner_agent ?? "(none)"} has not acknowledged contract rev ${task.contract_rev}`);
  }
  const pending = db
    .prepare("SELECT id FROM amendments WHERE task_id = ? AND status IN ('proposed','awaiting_human')")
    .all(taskId);
  if (pending.length > 0) throw new Refusal(`pending amendments must be resolved first: ${pending.map((row) => row.id).join(", ")}`);

  for (const dependencyId of contract.dependencies ?? []) {
    const dependency = getTask(db, dependencyId);
    if (!dependency || !["integrated", "done"].includes(dependency.state)) {
      throw new Refusal(`dependency ${dependencyId} is ${dependency?.state ?? "unknown"}; only integrated/done dependencies allow integration`);
    }
  }

  const branch = task.branch;
  const submitted = task.submitted_commit ?? task.head_commit;
  if (!branch || !submitted) throw new Refusal("task has no recorded branch/submitted commit");
  if ((policy.integration.protected_branches ?? []).includes(branch)) {
    throw new Refusal(`source branch ${branch} is protected; agents may not integrate from it`);
  }
  if (branch === target) throw new Refusal("source branch is the integration target");

  if (policy.integration.require_source_on_remote !== false) {
    const remoteLine = tryGit(repo, ["ls-remote", remote, `refs/heads/${branch}`]);
    if (!remoteLine) throw new Refusal(`branch ${branch} is not on ${remote}; push it before integrating`);
    const remoteSha = remoteLine.split(/\s+/)[0];
    if (remoteSha !== submitted) {
      throw new Refusal(
        `remote ${branch} is at ${remoteSha.slice(0, 8)}, expected submitted commit ${submitted.slice(0, 8)}. Push the branch and retry.`,
      );
    }
  }

  try {
    git(repo, ["fetch", remote]);
  } catch (error) {
    throw new Refusal(`could not fetch ${remote}: ${error.message}`);
  }
  const developRef = `refs/remotes/${remote}/${target}`;
  const developSha = tryGit(repo, ["rev-parse", developRef]);
  if (!developSha) throw new Refusal(`cannot resolve ${developRef}`);
  const localDevelop = tryGit(repo, ["rev-parse", `refs/heads/${target}`]);
  if (localDevelop !== developSha) {
    throw new Refusal(
      `local ${target} (${localDevelop?.slice(0, 8) ?? "missing"}) does not match ${remote}/${target} (${developSha.slice(0, 8)}); sync before integrating`,
    );
  }
  const checkedOut = developCheckedOut(repo);
  if (checkedOut) {
    throw new Refusal(`${target} is checked out at ${checkedOut.path}; the integrator updates the ref and refuses to desync a worktree`);
  }

  const mergeBase = git(repo, ["merge-base", developSha, submitted]);
  const changed = git(repo, ["diff", "--name-only", mergeBase, submitted])
    .split(/\r?\n/)
    .filter(Boolean);
  const violations = scopeViolations(changed, contract, { contractFile: entry.file });
  if (violations.length > 0) {
    throw new Refusal(
      `diff is outside the contract's authorized scope:\n${violations
        .map((violation) => `  - ${violation.file}: ${violation.reason}`)
        .join("\n")}`,
    );
  }

  const deploymentPolicy = policy.deployment ?? {};
  const allowedBranches = deploymentPolicy.allowed_branches ?? [];
  if (!allowedBranches.includes(target)) {
    throw new Refusal(`integration target "${target}" is not deployment-eligible per policy; refusing to push`);
  }
  const deploymentSensitive = changed.filter((file) => matchesAny(file, deploymentPolicy.sensitive_paths ?? []));
  if (deploymentSensitive.length > 0 && (contract.deployment_impact ?? "none") === "none") {
    throw new Refusal(
      `diff touches deployment-sensitive paths but the contract declares deployment_impact none:\n${deploymentSensitive
        .map((file) => `  - ${file}`)
        .join("\n")}\nDeclare deployment_impact (code/config) and deployment_verification via an amendment.`,
    );
  }

  if (tryGit(repo, ["merge-base", "--is-ancestor", submitted, developSha]) !== null) {
    updateTask(db, taskId, {
      state: "done",
      integrated_commit: developSha,
      blocked_reason: null,
    });
    recordEvent(db, { taskId, agent, kind: "already_integrated", message: `changes already in ${target}@${developSha.slice(0, 8)}` });
    return { alreadyIntegrated: true, develop: developSha, taskId };
  }

  const lock = acquireLock(db, {
    name: "integration",
    owner: agent,
    ttlSeconds: 20 * 60,
    purpose: taskId,
  });

  const candidate = candidatePathFor(taskId);
  let installedCandidate = false;
  try {
    git(repo, ["worktree", "add", "--detach", candidate, developSha]);
    installedCandidate = true;

    try {
      git(candidate, ["merge", "--no-ff", "--no-edit", submitted]);
    } catch (error) {
      const conflicts = tryGit(candidate, ["diff", "--name-only", "--diff-filter=U"]) ?? "";
      tryGit(candidate, ["merge", "--abort"]);
      fail(db, taskId, agent, "merge conflicts; source branch preserved", { conflicts });
      throw new Refusal(
        `merge failed (conflicts):\n${conflicts || error.message}\nThe task is marked integration_failed; resolve and resubmit.`,
      );
    }
    const mergeSha = git(candidate, ["rev-parse", "HEAD"]);
    const mergeTree = git(candidate, ["rev-parse", "HEAD^{tree}"]);

    // Dependency prepare: a fresh scratch worktree has no node_modules, and the
    // merge may add dependencies, so install against the post-merge (frozen)
    // lockfile before running the verification profile. Idempotent and fast when
    // already installed; tracked files are never modified.
    try {
      if (fs.existsSync(path.join(candidate, "pnpm-lock.yaml"))) {
        execFileSync("pnpm", ["install", "--frozen-lockfile", "--prefer-offline"], {
          cwd: candidate,
          stdio: "inherit",
          shell: true,
        });
        recordEvent(db, { taskId, agent, kind: "candidate_prepared", message: "pnpm install --frozen-lockfile" });
      }
    } catch (error) {
      recordEvent(db, {
        taskId,
        agent,
        kind: "candidate_prepare_failed",
        message: String(error?.message ?? error).slice(0, 500),
      });
    }

    const profileName = contract.verification_profile;
    const profile = policy.verification?.profiles?.[profileName];
    if (!profile) throw new Refusal(`verification profile "${profileName}" is not defined in plan/policy.yaml`);

    const verification = await (async () => {
      try {
        return await runProfile(db, repo, commonDir, {
          taskId,
          agent,
          profileName,
          profile,
          cwd: candidate,
          tree: mergeTree,
          commit: mergeSha,
          note: `integration candidate for ${taskId}@${submitted.slice(0, 8)} on ${target}@${developSha.slice(0, 8)}`,
          labelPrefix: `integrate-${taskId}`,
        });
      } catch (error) {
        if (error?.name === "ResourceDeferral") {
          recordEvent(db, { taskId, agent, kind: "integration_deferred", message: error.message });
          updateTask(db, taskId, { blocked_reason: `deferred: ${error.message}` });
          throw new ResourceDeferral(
            `Integration deferred by resource admission; ${target} is unchanged and the task remains submitted. ${error.message} Continue with light work or another eligible task and retry later.`,
          );
        }
        throw error;
      }
    })();
    if (verification.status !== "pass") {
      fail(db, taskId, agent, `integration verification failed (${profileName})`, {
        evidenceId: verification.evidenceId,
      });
      throw new Refusal(`integration verification failed (${profileName}); ${target} was not moved. See evidence ${verification.evidenceId}.`);
    }

    let migration = null;
    if ((contract.database_migration ?? "none") !== "none") {
      migration = await runDevelopmentMigration({ db, repo, commonDir, policy, agent, taskId });
      if (!migration.ok) {
        fail(db, taskId, agent, "development migration failed during integration", { migration });
        throw new Refusal("development migration failed; target branch was not moved");
      }
    }

    const evidenceDir = path.join(candidate, "plan", "evidence");
    fs.mkdirSync(evidenceDir, { recursive: true });
    fs.writeFileSync(
      path.join(evidenceDir, `${taskId}.md`),
      evidenceSummary({ taskId, contract, mergeSha, mergeTree, profile: profileName, result: verification, migration, agent }),
      "utf8",
    );
    git(candidate, ["add", "plan/evidence"]);
    git(candidate, ["commit", "-m", `chore(evidence): ${taskId} integration evidence`]);
    const finalCommit = git(candidate, ["rev-parse", "HEAD"]);

    git(repo, ["update-ref", `refs/heads/${target}`, finalCommit, developSha]);
    let pushError = null;
    try {
      git(repo, ["push", remote, `refs/heads/${target}:refs/heads/${target}`]);
    } catch (error) {
      pushError = error.message;
      // restore the local ref so local and remote stay consistent
      tryGit(repo, ["update-ref", `refs/heads/${target}`, developSha, finalCommit]);
      fail(db, taskId, agent, `push to ${remote}/${target} failed; local ${target} restored`, { pushError });
      throw new Refusal(`push failed: ${pushError}`);
    }
    const remoteAfter = (tryGit(repo, ["ls-remote", remote, `refs/heads/${target}`]) ?? "").split(/\s+/)[0];
    if (remoteAfter !== finalCommit) {
      recordEvent(db, {
        taskId,
        agent,
        kind: "integration_anomaly",
        message: `remote ${target} is ${remoteAfter?.slice(0, 8) ?? "unreadable"}, expected ${finalCommit.slice(0, 8)}`,
      });
      throw new Refusal(`remote ${target} does not match the integrated commit after push`);
    }

    const hasReview = (contract.acceptance ?? []).some((criterion) => /\[review\]/.test(criterion));
    const finalState = hasReview ? "integrated" : "done";
    db.prepare("UPDATE claims SET released_at = ?, release_reason = 'integrated' WHERE task_id = ? AND released_at IS NULL").run(
      new Date().toISOString(),
      taskId,
    );
    updateTask(db, taskId, {
      state: finalState,
      integrated_commit: finalCommit,
      integration_evidence_id: verification.evidenceId,
      blocked_reason: hasReview ? "review acceptance criteria pending" : null,
      owner_agent: null,
      owner_token: null,
      lease_expires_at: null,
    });
    recordEvent(db, {
      taskId,
      agent,
      kind: "integrated",
      message: `${target}@${finalCommit.slice(0, 8)} (verified merge ${mergeSha.slice(0, 8)})`,
      commit: finalCommit,
    });
    recordEvent(db, {
      taskId,
      agent,
      kind: "deployment_eligible_push",
      message: `${target} is allowlisted; the automatic deployment follows this push (no manual deploy)`,
      commit: finalCommit,
    });

    return {
      alreadyIntegrated: false,
      taskId,
      developBefore: developSha,
      developAfter: finalCommit,
      mergeCommit: mergeSha,
      evidenceId: verification.evidenceId,
      verification: verification.status,
      migration,
      state: finalState,
      remoteVerified: true,
      deployment: {
        branch: target,
        automatic: true,
        allowlisted: true,
        sensitiveFiles: deploymentSensitive,
      },
    };
  } finally {
    if (installedCandidate) {
      const cleanup = removeCandidate(repo, candidate);
      if (!cleanup.removed) {
        recordEvent(db, { taskId, agent, kind: "candidate_worktree_retained", message: cleanup.reason ?? "cleanup failed" });
      }
    }
    releaseLock(db, "integration", agent);
  }
}
